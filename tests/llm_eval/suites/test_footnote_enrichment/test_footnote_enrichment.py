from typing import Any

import mlflow
from mlflow.genai.evaluation.entities import Feedback
from langchain_litellm import ChatLiteLLM

import pytest
from llm_eval.suites.test_footnote_enrichment import data as harness_data
from llm_eval.suites.test_footnote_enrichment import scorers as harness_scorers
from llm_eval import core as harness_core
from llm_eval.conftest import suite_run

from paper_enrichment_agent.common.models import misc as misc_models
from paper_enrichment_agent.common.models import document as doc_models
from paper_enrichment_agent.common import document_manipulators
from paper_enrichment_agent.main_survey_enricher.components import arxiv_parser
from paper_enrichment_agent.common.http_client import HTTPClient


@mlflow.test
def test_footnote_enrichment_first_request(suite_run: harness_core.EvaluationRun) -> None:  # ruff: ignore[F811]
    """First footnote enrichment request sent to the agent.

    The footnote generated by the agent is evaluated by LLM Judges for its quality and relevance to
    the context of citation:
    1. Usefulness of figures extracted from the cited document.
    """

    run_config = suite_run.suite_config

    @harness_core.predict_with_typed_inputs
    @mlflow.trace(name='root_eval_span')
    async def predict(inputs: harness_data.FootnoteEnrichmentDSInputs) -> doc_models.Section:

        survey_doc = arxiv_parser.ArxivParser().parse(inputs.survey_arxiv_id)
        cited_doc = arxiv_parser.ArxivParser().parse(inputs.cited_document_arxiv_id)

        doc_getter = document_manipulators.DocumentGetter(survey_doc)

        referencing_paragraph = doc_getter.get_component_by_path(inputs.citing_paragraph_path)

        assert isinstance(referencing_paragraph, doc_models.Paragraph)

        request = misc_models.FootnoteEnrichmentRequest(
            survey_title=survey_doc.title,
            survey_abstract=survey_doc.abstract,
            reference_document=cited_doc,
            reference_document_title=cited_doc.title,
            reference_id=inputs.reference_id,
            referencing_paragraph=referencing_paragraph,
            citation_context_info=inputs.citation_context,
        )

        http_client = HTTPClient(
            base_url=run_config['footnote_enrichment_service_url'],
            timeout=run_config['enrichment_service_reuqest_timeout'],
        )

        return await http_client.apost(
            '/reference_to_footnote', request, response_schema=doc_models.Section
        )

    mlflow.log_params({'dataset_name': run_config['datasets']['footnote_enrichment']})

    eval_dataset = harness_core.load_dataset(
        run_config['datasets']['footnote_enrichment'],
        inputs_type=harness_data.FootnoteEnrichmentDSInputs,
    )

    judge_llm = ChatLiteLLM(
        model=run_config['judge_llm_config']['model_name'],
        api_key=run_config['judge_llm_config']['api_key'],
        **run_config['judge_llm_config'].get('model_params', {}),
    )

    eval_results = mlflow.genai.evaluate(
        eval_dataset, [harness_scorers.spawn_figure_usefulness_rating(judge_llm)], predict
    )

    fail_reason = harness_core.validate_results(
        suite_run.mlflow_run.info.run_id,
        eval_results,
        run_config['thresholds']['footnote_enrichment'],
    )

    if fail_reason:
        pytest.fail(fail_reason)
